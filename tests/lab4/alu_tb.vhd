library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use std.env.all;
use work.alu_types_pkg.all;

entity alu_tb is
end entity alu_tb;

architecture sim of alu_tb is
    signal A         : std_logic_vector(15 downto 0) := (others => '0');
    signal B         : std_logic_vector(15 downto 0) := (others => '0');
    signal opcode    : std_logic_vector(2 downto 0)  := "000";
    signal flags_in  : alu_flags := ('0', '0', '0', '0');

    signal C         : std_logic_vector(31 downto 0);
    signal flags_out : alu_flags;
begin

    dut : entity work.alu
        port map (
            A         => A,
            B         => B,
            opcode    => opcode,
            flags_in  => flags_in,
            C         => C,
            flags_out => flags_out
        );

    stimulus : process
        procedure check_op(
            in_op    : std_logic_vector(2 downto 0);
            in_a     : std_logic_vector(15 downto 0);
            in_b     : std_logic_vector(15 downto 0);
            in_flags : alu_flags;
            exp_c    : std_logic_vector(31 downto 0);
            exp_n    : std_logic;
            exp_z    : std_logic;
            exp_v    : std_logic;
            exp_c_fl : std_logic;
            msg      : string
        ) is
        begin
            opcode   <= in_op;
            A        <= in_a;
            B        <= in_b;
            flags_in <= in_flags;
            wait for 10 ns;

            assert C = exp_c
                report "FAIL [" & msg & "] C mismatch: got " & to_hstring(C) & ", expected " & to_hstring(exp_c)
                severity failure;

            assert flags_out.N = exp_n
                report "FAIL [" & msg & "] Flag N mismatch"
                severity failure;

            assert flags_out.Z = exp_z
                report "FAIL [" & msg & "] Flag Z mismatch"
                severity failure;

            assert flags_out.V = exp_v
                report "FAIL [" & msg & "] Flag V mismatch"
                severity failure;

            assert flags_out.C = exp_c_fl
                report "FAIL [" & msg & "] Flag C mismatch"
                severity failure;
        end procedure;
    begin
        -- =====================================================================
        -- 1. Базовые проверки простых/уже протестированных операций
        -- =====================================================================
        -- 000: NOT (проверяем инверсию, N=1, Z=0 и сохранение V=1, C=1)
        check_op("000", x"00FF", x"1234", ('0', '0', '1', '1'),
                 x"0000FF00", '1', '0', '1', '1', "NOT basic");

        -- 001: ADD CLA (сквозной перенос + входной перенос C_in=1 -> результат 0, Z=1, C=1)
        check_op("001", x"FFFF", x"0000", ('0', '0', '0', '1'),
                 x"00000000", '0', '1', '0', '1', "ADD CLA with carry");

        -- 101: ADD RCA (те же входы -> идентичный результат)
        check_op("101", x"FFFF", x"0000", ('0', '0', '0', '1'),
                 x"00000000", '0', '1', '0', '1', "ADD RCA with carry");

        -- 011: XOR (равные числа -> результат 0, Z=1, сохранение V=1, C=0)
        check_op("011", x"A5A5", x"A5A5", ('1', '0', '1', '0'),
                 x"00000000", '0', '1', '1', '0', "XOR equal values");

        -- =====================================================================
        -- 2. Циклический сдвиг (opcode = "100"): крайние случаи + 2 стандартных
        -- =====================================================================
        -- Крайний 1: Сдвиг на 0 (результат не меняется, C берется из flags_in.C = 1)
        check_op("100", x"8001", x"0000", ('0', '0', '0', '1'),
                 x"00008001", '1', '0', '0', '1', "SHIFT by 0");

        -- Крайний 2: Нулевое слово (Z=1, C=0)
        check_op("100", x"0000", x"0005", ('0', '0', '0', '1'),
                 x"00000000", '0', '1', '0', '0', "SHIFT zero word");

        -- Крайний 3: Полный оборот на -16 (5-битное знаковое 10000 = -16 -> слово возвращается в исходное)
        check_op("100", x"1234", x"0010", ('0', '0', '0', '0'),
                 x"00001234", '0', '0', '0', '0', "SHIFT by -16 (full rotation)");
        
        -- Стандартный 1: Сдвиг влево на +4 (0x1234 -> 0x2341, вытолкнутый бит попал в C=1)
        check_op("100", x"0005", x"0001", ('0', '0', '0', '0'),
                 x"0000000A", '0', '0', '0', '0', "SHIFT left by +1");

        -- Стандартный 2: Сдвиг влево на +4 (0x1234 -> 0x2341, вытолкнутый бит попал в C=1)
        check_op("100", x"1234", x"0004", ('0', '0', '0', '0'),
                 x"00002341", '0', '0', '0', '1', "SHIFT left by +4");

        -- Стандартный 3: Сдвиг вправо на -4 (B = -4 = 0xFFFC -> 0x1234 -> 0x4123, старший бит 0 -> C=0)
        check_op("100", x"1234", x"FFFC", ('0', '0', '0', '1'),
                 x"00004123", '0', '0', '0', '0', "SHIFT right by -4");

        -- =====================================================================
        -- 3. Беззнаковое умножение (opcode = "010"): крайние + разные области
        -- =====================================================================
        -- Крайний 1: Умножение на 0 (Z=1, V=0, C=0)
        check_op("010", x"FFFF", x"0000", ('1', '0', '1', '1'),
                 x"00000000", '0', '1', '0', '0', "MUL_U by zero");

        -- Крайний 2: Максимальные беззнаковые (65535 * 65535 = 0xFFFE0001 -> переполнение 16 бит V=1, C=1)
        check_op("010", x"FFFF", x"FFFF", ('0', '0', '0', '0'),
                 x"FFFE0001", '0', '0', '1', '1', "MUL_U max * max");

        -- Область 1: Малые числа, помещающиеся в 16 бит (200 * 300 = 60000 = 0xEA60 -> V=0, C=0)
        check_op("010", x"00C8", x"012C", ('0', '0', '0', '0'),
                 x"0000EA60", '0', '0', '0', '0', "MUL_U fits in 16 bit");

        -- Область 2: Граница выхода за 16 бит (256 * 256 = 65536 = 0x00010000 -> V=1, C=1)
        check_op("010", x"0100", x"0100", ('0', '0', '0', '0'),
                 x"00010000", '0', '0', '1', '1', "MUL_U exact 16-bit overflow");

        -- Область 3: Старшие биты без знаковой интерпретации (0x8000 * 2 = 65536 = 0x00010000 -> N=0!)
        check_op("010", x"8000", x"0002", ('0', '0', '0', '0'),
                 x"00010000", '0', '0', '1', '1', "MUL_U MSB set");

        -- =====================================================================
        -- 4. Знаковое умножение (opcode = "110"): крайние + разные области
        -- =====================================================================
        -- Крайний 1: Умножение на 0 (Z=1, N=0, V=0, C=0)
        check_op("110", x"8000", x"0000", ('0', '0', '0', '0'),
                 x"00000000", '0', '1', '0', '0', "MUL_S by zero");

        -- Крайний 2: Минимум * Минимум (-32768 * -32768 = +1073741824 = 0x40000000 -> N=0, V=1, C=1)
        check_op("110", x"8000", x"8000", ('0', '0', '0', '0'),
                 x"40000000", '0', '0', '1', '1', "MUL_S min * min");

        -- Область 1: Положительное * Положительное в пределах 16 бит (+100 * +200 = +20000 = 0x4E20 -> V=0)
        check_op("110", x"0064", x"00C8", ('0', '0', '0', '0'),
                 x"00004E20", '0', '0', '0', '0', "MUL_S pos * pos fits");

        -- Область 2: Положительное * Отрицательное в пределах 16 бит (-1 * +2 = -2 = 0xFFFFFFFE -> N=1, V=0!)
        check_op("110", x"FFFF", x"0002", ('0', '0', '0', '0'),
                 x"FFFFFFFE", '1', '0', '0', '0', "MUL_S neg * pos fits");

        -- Область 3: Отрицательное * Отрицательное в пределах 16 бит (-100 * -200 = +20000 -> N=0, V=0)
        check_op("110", x"FF9C", x"FF38", ('0', '0', '0', '0'),
                 x"00004E20", '0', '0', '0', '0', "MUL_S neg * neg fits");

        -- Область 4: Знаковое переполнение 16 бит (+200 * +200 = +40000 = 0x00009C40 -> 15-й бит=1, но число > 0 -> V=1!)
        check_op("110", x"00C8", x"00C8", ('0', '0', '0', '0'),
                 x"00009C40", '0', '0', '1', '1', "MUL_S pos overflow 16-bit");

        -- Область 5: Отрицательное переполнение 16 бит (-200 * +200 = -40000 = 0xFFFF63C0 -> N=1, V=1!)
        check_op("110", x"FF38", x"00C8", ('0', '0', '0', '0'),
                 x"FFFF63C0", '1', '0', '1', '1', "MUL_S neg overflow 16-bit");

        -- =====================================================================
        -- 5. Проверка дефолтной ветки (opcode = "111")
        -- =====================================================================
        check_op("111", x"1234", x"5678", ('1', '0', '1', '0'),
                 x"00000000", '1', '0', '1', '0', "Default opcode 111");

        report "ALL ALU TESTS PASSED SUCCESSFULLY!" severity note;
        wait for 10 ns;
        wait for 1 ns;
        finish;
    end process;

end architecture sim;
